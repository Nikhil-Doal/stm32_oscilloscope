void apply_hann_window(uint16_t *src, float *dst, int len) {
	for (int i = 0; i < len; ++i) {
		float window = 0.5f * (1.0f - cosf(2.0f * M_PI * i / (len - 1)));
		dst[i] = (float)src[i] * window;
	}
}
